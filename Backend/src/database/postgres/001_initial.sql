-- Supabase의 public/auth 스키마와 분리된 백엔드 전용 스키마입니다.
-- 마이그레이션 실행기가 트랜잭션과 버전 잠금을 관리합니다.
CREATE TABLE mentos.user_accounts (
  id VARCHAR(50) PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  room_number VARCHAR(10) NOT NULL DEFAULT '',
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(10) NOT NULL DEFAULT 'STUDENT' CHECK (role IN ('STUDENT', 'ADMIN')),
  status VARCHAR(15) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE mentos.login_sessions (
  token_hash CHAR(64) PRIMARY KEY,
  account_id VARCHAR(50) NOT NULL REFERENCES mentos.user_accounts(id) ON UPDATE CASCADE ON DELETE CASCADE,
  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX login_sessions_account_idx ON mentos.login_sessions(account_id);
CREATE INDEX login_sessions_expiry_idx ON mentos.login_sessions(expires_at);

CREATE TABLE mentos.attendance_records (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id VARCHAR(50) NOT NULL REFERENCES mentos.user_accounts(id) ON UPDATE CASCADE,
  attendance_date DATE NOT NULL,
  period VARCHAR(10) NOT NULL CHECK (period IN ('MORNING', 'LUNCH', 'EVENING')),
  status VARCHAR(10) NOT NULL DEFAULT 'PRESENT' CHECK (status IN ('PRESENT', 'LATE', 'ABSENT', 'EXCUSED')),
  checked_at TIMESTAMPTZ,
  recorded_by VARCHAR(50) NOT NULL REFERENCES mentos.user_accounts(id) ON UPDATE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE (student_id, attendance_date, period)
);
CREATE INDEX attendance_date_period_idx ON mentos.attendance_records(attendance_date, period);

CREATE TABLE mentos.leave_applications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id VARCHAR(50) NOT NULL REFERENCES mentos.user_accounts(id) ON UPDATE CASCADE,
  type VARCHAR(10) NOT NULL CHECK (type IN ('OUTING', 'HOME_VISIT')),
  starts_at TIMESTAMPTZ NOT NULL,
  ends_at TIMESTAMPTZ NOT NULL,
  reason VARCHAR(500) NOT NULL DEFAULT '',
  status VARCHAR(10) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED', 'CANCELLED')),
  reviewed_by VARCHAR(50) REFERENCES mentos.user_accounts(id) ON UPDATE CASCADE,
  reviewed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (ends_at > starts_at)
);
CREATE INDEX leaves_student_period_idx ON mentos.leave_applications(student_id, starts_at, ends_at);
CREATE INDEX leaves_status_start_idx ON mentos.leave_applications(status, starts_at);

CREATE FUNCTION mentos.touch_updated_at() RETURNS TRIGGER LANGUAGE plpgsql
SET search_path = pg_catalog, mentos AS $body$
BEGIN
  NEW.updated_at = CURRENT_TIMESTAMP;
  RETURN NEW;
END;
$body$;
CREATE TRIGGER user_accounts_updated BEFORE UPDATE ON mentos.user_accounts
  FOR EACH ROW EXECUTE FUNCTION mentos.touch_updated_at();
CREATE TRIGGER attendance_updated BEFORE UPDATE ON mentos.attendance_records
  FOR EACH ROW EXECUTE FUNCTION mentos.touch_updated_at();
CREATE TRIGGER leaves_updated BEFORE UPDATE ON mentos.leave_applications
  FOR EACH ROW EXECUTE FUNCTION mentos.touch_updated_at();

-- 브라우저/Data API에서 계정과 세션을 직접 조회하지 못하게 합니다.
ALTER TABLE mentos.user_accounts ENABLE ROW LEVEL SECURITY;
ALTER TABLE mentos.login_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE mentos.attendance_records ENABLE ROW LEVEL SECURITY;
ALTER TABLE mentos.leave_applications ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA mentos FROM PUBLIC;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA mentos FROM PUBLIC;
REVOKE ALL ON FUNCTION mentos.touch_updated_at() FROM PUBLIC;
